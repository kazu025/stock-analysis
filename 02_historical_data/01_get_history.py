"""
Yahoo Financeからキヤノン（7751）の過去株価を取得し、
直近250営業日の高値・安値・値幅率を計算する。

処理の流れ:
1. yfinanceから過去2年間の株価を取得する
2. 直近250営業日のデータを取り出す
3. 250営業日の高値・安値を求める
4. 高値と安値から値幅率を計算する
"""

import yfinance as yf

# Yahoo finance 塩野義製薬 銘柄コード
SYMBOLNAME = "塩野義製薬"
TICKER = "4507.T"

# 分析対象とする営業日数
DAYS = 250

# -------------------------------------------------- 
# 1.過去２年の年間株価を取得する
# -------------------------------------------------- 
stock = yf.Ticker(TICKER)

df = stock.history(
    period='2y',
    auto_adjust=False
)
# -------------------------------------------------- 
# 2.直近250の営業データを取り出す。
# -------------------------------------------------- 
df250 = df.tail(DAYS)

# -------------------------------------------------- 
# 3.データの内容を確認する
# -------------------------------------------------- 
print("=== データ取得結果 ===")
print(f"銘柄              : {SYMBOLNAME}({TICKER})")
print(f"取得した全データ数 : {len(df):4d}")
print(f"分析対象データ数   : {len(df250):4d}")

print()

print("=== 直近5営業日 ===")
print(df250.tail())

# -------------------------------------------------- 
# 4.250営業日の高値・安値を求める
# -------------------------------------------------- 
high_250 = df250["High"].max()
low_250 = df250["Low"].min()
# --------------------------------------------------
# 5. 値幅率を計算する
# --------------------------------------------------

range_pct = (high_250 - low_250) / low_250 * 100


print()

print("=== 250営業日分析 ===")
print(f"250日高値 : {high_250:10.1f} 円")
print(f"250日安値 : {low_250:10.1f} 円")
print(f"値幅      : {high_250 - low_250:10.1f} 円")
print(f"値幅率    : {range_pct:10.1f} %")
