"""
塩野義製薬（4507）の直近60営業日の株価について、
レンジ上側・下側への到達状況を調べる。

目的:
1. 直近60営業日の高値・安値を求める
2. 株価レンジの上側20%・下側20%をゾーンとして定義する
3. 終値が各ゾーンに入った営業日を数える
4. うねりとして上下を繰り返しているか調べる準備をする

今回は「ゾーン内にいた営業日数」を数える。
連続した営業日を1回の到達として数える処理は次の段階で行う。
"""

import yfinance as yf


TICKER = "4507.T"
SYMBOL_NAME = "塩野義製薬"

RANGE_DAYS = 60

# レンジの上側・下側何%をゾーンとするか
ZONE_RATIO = 0.20


# --------------------------------------------------
# 1. 過去2年間の株価を取得する
# --------------------------------------------------

stock = yf.Ticker(TICKER)

df = stock.history(
    period="2y",
    auto_adjust=False
)


# --------------------------------------------------
# 2. 直近60営業日を取り出す
# --------------------------------------------------

df_range = df.tail(RANGE_DAYS).copy()


# --------------------------------------------------
# 3. 60営業日の高値・安値・値幅を求める
# --------------------------------------------------

range_high = df_range["High"].max()
range_low = df_range["Low"].min()

price_range = range_high - range_low


# --------------------------------------------------
# 4. 上側・下側ゾーンの境界を計算する
# --------------------------------------------------

upper_zone = range_high - price_range * ZONE_RATIO
lower_zone = range_low + price_range * ZONE_RATIO


# --------------------------------------------------
# 5. 終値がゾーン内にあるか判定する
# --------------------------------------------------

df_range["UpperZone"] = df_range["Close"] >= upper_zone
df_range["LowerZone"] = df_range["Close"] <= lower_zone


# --------------------------------------------------
# 6. ゾーン内にいた営業日数を数える
# --------------------------------------------------

upper_days = df_range["UpperZone"].sum()
lower_days = df_range["LowerZone"].sum()


# --------------------------------------------------
# 7. 結果を表示する
# --------------------------------------------------

print("=== レンジ・ゾーン分析 ===")
print(f"銘柄       : {SYMBOL_NAME} ({TICKER})")
print(f"分析期間   : {RANGE_DAYS} 営業日")
print()

print("=== レンジ ===")
print(f"安値       : {range_low:8.1f} 円")
print(f"高値       : {range_high:8.1f} 円")
print(f"値幅       : {price_range:8.1f} 円")

print()

print("=== ゾーン ===")
print(f"上側境界   : {upper_zone:8.1f} 円")
print(f"下側境界   : {lower_zone:8.1f} 円")
print(f"ゾーン幅   : {ZONE_RATIO * 100:8.1f} %")

print()

print("=== ゾーン内営業日数 ===")
print(f"上側ゾーン : {upper_days:4d} 日")
print(f"下側ゾーン : {lower_days:4d} 日")