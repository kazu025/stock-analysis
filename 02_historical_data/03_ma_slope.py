"""
塩野義製薬（4507）の移動平均線の変化率を計算する。

目的:
1. 25日移動平均（MA25）を計算する
2. 75日移動平均（MA75）を計算する
3. 現在と20営業日前の移動平均を比較する
4. 移動平均の傾向を変化率として数値化する

これにより、チャートを目で見て判断していた
「上昇」「下降」「横ばい」を数値で表現する。
"""

import yfinance as yf


TICKER = "4507.T"
SYMBOL_NAME = "塩野義製薬"

DAYS = 250

MA25_DAYS = 25
MA75_DAYS = 75

# 何営業日前と比較するか
COMPARE_DAYS = 20


# --------------------------------------------------
# 1. 過去2年間の株価を取得する
# --------------------------------------------------

stock = yf.Ticker(TICKER)

df = stock.history(
    period="2y",
    auto_adjust=False
)


# --------------------------------------------------
# 2. 直近250営業日を取り出す
# --------------------------------------------------

df250 = df.tail(DAYS).copy()


# --------------------------------------------------
# 3. 移動平均を計算する
# --------------------------------------------------

df250["MA25"] = (
    df250["Close"]
    .rolling(MA25_DAYS)
    .mean()
)

df250["MA75"] = (
    df250["Close"]
    .rolling(MA75_DAYS)
    .mean()
)


# --------------------------------------------------
# 4. 現在と20営業日前の移動平均を取得する
# --------------------------------------------------

ma25_current = df250["MA25"].iloc[-1]
ma25_previous = df250["MA25"].iloc[-1 - COMPARE_DAYS]

ma75_current = df250["MA75"].iloc[-1]
ma75_previous = df250["MA75"].iloc[-1 - COMPARE_DAYS]


# --------------------------------------------------
# 5. 移動平均の変化率を計算する
# --------------------------------------------------

ma25_change_pct = (
    (ma25_current - ma25_previous)
    / ma25_previous
    * 100
)

ma75_change_pct = (
    (ma75_current - ma75_previous)
    / ma75_previous
    * 100
)


# --------------------------------------------------
# 6. 結果を表示する
# --------------------------------------------------

print("=== 移動平均の変化率 ===")
print(f"銘柄              : {SYMBOL_NAME} ({TICKER})")
print(f"比較期間          : {COMPARE_DAYS} 営業日")
print()

print("=== MA25 ===")
print(f"{COMPARE_DAYS}日前 : {ma25_previous:8.1f} 円")
print(f"現在             : {ma25_current:8.1f} 円")
print(f"変化率           : {ma25_change_pct:+8.2f} %")

print()

print("=== MA75 ===")
print(f"{COMPARE_DAYS}日前 : {ma75_previous:8.1f} 円")
print(f"現在             : {ma75_current:8.1f} 円")
print(f"変化率           : {ma75_change_pct:+8.2f} %")